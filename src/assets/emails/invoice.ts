type TGetInvoiceEmailTemplate = { quoteData:  Quote & { products: Product[] } }

export function getInvoiceEmailTemplate({ quoteData }: TGetInvoiceEmailTemplate) {
    const { products = [] } = quoteData;
    const prices = getTotalPrices({ products });

    return InvoiceTemplate
        .replace(INVOICE_PLACEHOLDER.INVOICE_ID, `INV-${quoteData.id}`)
        .replace(INVOICE_PLACEHOLDER.ISSUE_DATE, format(new Date(), `MMM. dd, yyyy`))
        .replace(INVOICE_PLACEHOLDER.CUSTOMER_NAME, `${quoteData.firstName} ${quoteData.lastName}` )
        .replace(INVOICE_PLACEHOLDER.CUSTOMER_ADDRESS, Address({ quoteData }))
        .replace(INVOICE_PLACEHOLDER.ORDER_NUMBER, quoteData.id)
        .replace(INVOICE_PLACEHOLDER.ROWS_OF_SERVIECS, ServiceRow({ products }))
        .replace(INVOICE_PLACEHOLDER.SUBTOTAL_PRICE, Subtotal(prices.subTotal))
        // TODO: Check what is the difference between subtotal and this.
        .replace(INVOICE_PLACEHOLDER.TOTAL_EXCLUDE_VAT, TotalExcVat(prices.subTotal))
        .replace(INVOICE_PLACEHOLDER.TOTAL_VAT, TotalVat(prices.totalVat))
        .replace(INVOICE_PLACEHOLDER.TOTAL_AMOUNT, TotalAmout(prices.totalAmount))
        // TODO: Update amount paid - Installment?
        .replace(INVOICE_PLACEHOLDER.AMOUNT_PAID, AmountPaid(prices.totalAmount));
}